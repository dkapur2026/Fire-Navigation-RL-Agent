"""The adaptive-agent study (WP-F): how much of the baseline-to-oracle gap it closes, how fast, at what cost.

    python scripts/adaptive_study.py              # 100 seeds per cell, all cores, ~5 min; writes docs/adaptive_study.md
    python scripts/adaptive_study.py --seeds 20 --out /tmp/study.md

Every household x novelty on the ranch, same seeds (same fires) for every agent:
  * score / success / gap_closed with 95% paired-bootstrap intervals;
  * ablations: no detector (= baseline), detector + posterior-mean flip (``naive_repair``), full pipeline;
  * false alarms on ``none`` and detection delay on every novel rule;
  * recovery curve: the score of an oracle that only learns each change ``k`` ticks after it happened, next to
    the share of adaptive episodes whose belief has the change by then. Together they say how quickly the truth
    must arrive to be worth anything, and how often evidence arrives that quickly;
  * cost: wall-clock per episode and per tick, and repair calls per episode.
"""

from __future__ import annotations

import argparse
import os
import statistics
import time
from concurrent.futures import ProcessPoolExecutor
from functools import partial
from pathlib import Path

from emberpath.agents import OracleAgent
from emberpath.blueprint import Blueprint
from emberpath.dependents import HOUSEHOLDS
from emberpath.evaluate import EpisodeResult, gap_ratio, paired_bootstrap, run_episode
from emberpath.rules import nominal_rules
from emberpath.scenarios import NOVELTIES
from make_results import MIN_GAP, PROFILES, ROOT, ci
from make_results import NOVELTIES as SCENARIOS

AGENTS = ["baseline", "oracle", "adaptive", "naive_repair"]
LAGS = [0, 1, 2, 3, 5, 8, 13, 20, 30, 45, 60]


def ranch() -> Blueprint:
    return Blueprint.from_file(ROOT / "blueprints" / "ranch.txt")


class LateOracle(OracleAgent):
    """An oracle that learns each true rule change only ``lag`` ticks after it happens."""

    def __init__(self, blueprint, world, lag: int):
        super().__init__(blueprint, world)
        self.lag, self.name = lag, f"oracle+{lag}"

    def act(self, obs, events):
        known = [p for t, p in self.world.novelty_log if t + self.lag <= obs.step]
        self.planner.belief = nominal_rules().with_patches(known)
        return self.planner.act(obs)


def eval_job(args) -> tuple[str, str | None, list[EpisodeResult], dict[str, float]]:
    profile, novelty, seeds = args
    bp, hh = ranch(), HOUSEHOLDS[profile]
    results, secs = [], dict.fromkeys(AGENTS, 0.0)
    for agent in AGENTS:
        for s in range(seeds):
            t0 = time.perf_counter()
            results.append(run_episode(bp, hh, agent, novelty, s))
            secs[agent] += time.perf_counter() - t0
    return profile, novelty, results, secs


def lag_job(args) -> tuple[str, str, int, float]:
    profile, novelty, lag, seeds = args
    bp, hh = ranch(), HOUSEHOLDS[profile]
    scores = [run_episode(bp, hh, partial(LateOracle, lag=lag), novelty, s).score for s in range(seeds)]
    return profile, novelty, lag, sum(scores) / len(scores)


def recovered_at(r: EpisodeResult, key: str, truth: float) -> int | None:
    """Tick at which the agent's belief about ``key`` first moved closer to the truth than the nominal value."""
    nominal = nominal_rules().prob(key)
    for t, k, v in r.patches:
        if k == key and abs(v - truth) < abs(nominal - truth):
            return t
    return None


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--seeds", type=int, default=100)
    ap.add_argument("--lag-seeds", type=int, default=60)
    ap.add_argument("--out", default=str(ROOT / "docs" / "adaptive_study.md"))
    a = ap.parse_args()
    bp = ranch()
    specs = {(p, n): NOVELTIES[n](bp, HOUSEHOLDS[p]) for p in PROFILES for n in SCENARIOS if n}

    t0 = time.perf_counter()
    with ProcessPoolExecutor(os.cpu_count()) as pool:
        evals = list(pool.map(eval_job, [(p, n, a.seeds) for p in PROFILES for n in SCENARIOS]))
        lags = list(pool.map(lag_job, [(p, n, k, a.lag_seeds) for (p, n) in specs for k in LAGS]))
    wall = time.perf_counter() - t0

    L = [
        f"# Adaptive-agent study: ranch blueprint, {a.seeds} seeds per cell",
        "",
        f"Generated by `python scripts/adaptive_study.py --seeds {a.seeds} --lag-seeds {a.lag_seeds}` "
        f"({wall:.0f} s wall on {os.cpu_count()} cores). Score = fraction of dependents rescued, 0 if the rescuer dies.",
        "Same seeds and fires for every agent; brackets are 95% paired-bootstrap intervals over seeds.",
        f"`gap closed` = (agent - baseline) / (oracle - baseline), `n/a` when the oracle gap is under {MIN_GAP}.",
        "",
        "## 1. Headline and ablations",
        "",
        "`baseline` = no detector; `naive_repair` = detector, flagged rules jump to their posterior mean (no search);",
        "`adaptive` = detector + repair search.",
        "",
        "| household | novelty | baseline | oracle | naive_repair | adaptive | gap closed: naive | gap closed: adaptive "
        "| success b / o / a |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for p, n, res, _ in evals:
        m = {ag: paired_bootstrap(res, lambda x, ag=ag: x[ag]) for ag in AGENTS}
        succ = {
            ag: paired_bootstrap(res, lambda x, ag=ag: x[ag], value=lambda r: float(r.outcome == "success"))[0]
            for ag in ("baseline", "oracle", "adaptive")
        }
        big = m["oracle"][0] - m["baseline"][0] >= MIN_GAP
        gaps = [ci(*paired_bootstrap(res, gap_ratio(ag)), pct=True) if big else "n/a" for ag in ("naive_repair", "adaptive")]
        L.append(
            f"| {p} | {n or 'none'} | {m['baseline'][0]:.2f} | {m['oracle'][0]:.2f} | {ci(*m['naive_repair'])} "
            f"| {ci(*m['adaptive'])} | {gaps[0]} | {gaps[1]} "
            f"| {succ['baseline']:.0%} / {succ['oracle']:.0%} / {succ['adaptive']:.0%} |"
        )

    L += [
        "",
        "## 2. False alarms and detection delay (adaptive agent)",
        "",
        "False alarm (`none`): the episode's belief was edited at all. Recovered: the belief about the changed rule",
        "moved closer to the truth than the textbook value. Delay: ticks from the change to that edit (median, quartiles),",
        "over recovered episodes. Wrong edits: episodes with an edit to a rule that did not change.",
        "",
        "| household | novelty | changed rule | recovered | delay median [q1, q3] | wrong edits | false alarms on none |",
        "|---|---|---|---|---|---|---|",
    ]
    for p, n, res, _ in evals:
        ad = [r for r in res if r.agent == "adaptive"]
        if n is None:
            fa = sum(bool(r.patches) for r in ad) / len(ad)
            L.append(f"| {p} | none | - | - | - | - | {fa:.1%} ({sum(bool(r.patches) for r in ad)}/{len(ad)}) |")
            continue
        novel = {s.patch.key for s in specs[p, n]}
        wrong = sum(any(k not in novel for _, k, _ in r.patches) for r in ad) / len(ad)
        for s in specs[p, n]:
            ts = [recovered_at(r, s.patch.key, float(s.patch.value)) for r in ad]
            d = sorted(t - s.step for t in ts if t is not None)
            delay = f"{statistics.median(d):g} [{d[len(d) // 4]}, {d[(3 * len(d)) // 4]}]" if d else "n/a"
            L.append(
                f"| {p} | {n} | `{s.patch.key}` (t={s.step}) | {len(d) / len(ad):.0%} | {delay} | {wrong:.0%} | - |"
            )

    L += [
        "",
        "## 3. Recovery curve",
        "",
        f"`oracle+k`: mean score of an oracle that learns each change k ticks after it happens ({a.lag_seeds} seeds).",
        "`adaptive by k`: share of adaptive episodes whose belief had every change by then (same definition as section 2).",
        "",
        "| household | novelty | | " + " | ".join(f"k={k}" for k in LAGS) + " |",
        "|---|---|---|" + "---|" * len(LAGS),
    ]
    lag_score = {(p, n, k): v for p, n, k, v in lags}
    ad_by_cell = {(p, n): [r for r in res if r.agent == "adaptive"] for p, n, res, _ in evals}
    for (p, n), sp in specs.items():
        ad = ad_by_cell[p, n]

        def by(k: int, r: EpisodeResult) -> bool:
            ts = [recovered_at(r, s.patch.key, float(s.patch.value)) for s in sp]
            return all(t is not None and t - s.step <= k for t, s in zip(ts, sp))

        L.append(f"| {p} | {n} | oracle+k | " + " | ".join(f"{lag_score[p, n, k]:.2f}" for k in LAGS) + " |")
        L.append("| | | adaptive by k | " + " | ".join(f"{sum(by(k, r) for r in ad) / len(ad):.0%}" for k in LAGS) + " |")

    L += ["", "## 4. Cost", "", "| agent | ms / episode | us / tick | repair calls / episode |", "|---|---|---|---|"]
    for ag in AGENTS:
        rows = [r for _, _, res, _ in evals for r in res if r.agent == ag]
        secs = sum(s[ag] for *_, s in evals)
        L.append(
            f"| {ag} | {1000 * secs / len(rows):.0f} | {1e6 * secs / sum(r.steps for r in rows):.0f} "
            f"| {sum(r.repair_calls for r in rows) / len(rows):.2f} |"
        )
    L += ["", "Wall-clock is measured inside parallel workers, so compare rows with each other, not with a laptop."]

    out = Path(a.out)
    out.write_text("\n".join(L) + "\n")
    print("\n".join(L))
    print(f"\nwrote {out}")


if __name__ == "__main__":
    main()
